// Writes config/shared/archonShardCatalog.ts from warframe-worldstate-data's
// archonShards.json (installed with @wfcd/items). DE's public export has no
// list of shard effects, so this is the only source. Rerun after a shard update:
//   node scripts/build-archon-shard-catalog.mjs

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const source = path.join(
  root,
  "node_modules",
  "warframe-worldstate-data",
  "dist",
  "data",
  "archonShards.json",
);
const target = path.join(root, "config", "shared", "archonShardCatalog.ts");

const data = JSON.parse(fs.readFileSync(source, "utf8"));
const entries = [];
for (const [color, group] of Object.entries(data)) {
  for (const [type, effect] of Object.entries(group.upgradeTypes ?? {})) {
    // Upstream text carries a typo and an in-game icon token.
    const text = String(effect.value ?? "")
      .replace(/\bSheild\b/g, "Shield")
      .replace(/\bDmg[A-Za-z]+\d*\s*/g, "")
      .replace(/\s+/g, " ")
      .trim();
    if (text) entries.push({ color, type, effect: text });
  }
}
entries.sort((a, b) => a.color.localeCompare(b.color) || a.type.localeCompare(b.type));

const lines = [
  "// Generated by scripts/build-archon-shard-catalog.mjs, do not edit.",
  "// Source: warframe-worldstate-data archonShards.json (WFCD, MIT).",
  "",
  "interface ArchonShardEffect {",
  "  /** Socket colour as the inventory writes it; _MYTHIC is tauforged. */",
  "  color: string;",
  "  type: string;",
  "  /** English effect text at that shard's strength. */",
  "  effect: string;",
  "}",
  "",
  "export const ARCHON_SHARD_EFFECTS: readonly ArchonShardEffect[] = Object.freeze([",
  ...entries.map((e) => `  ${JSON.stringify(e)},`),
  "]);",
  "",
];
fs.writeFileSync(target, lines.join("\n"));
console.log(`wrote ${entries.length} shard effects to ${path.relative(root, target)}`);
